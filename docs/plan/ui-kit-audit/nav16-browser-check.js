const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const outputDir = process.env.OUTPUT_DIR || __dirname;
const baseUrl = process.env.BASE_URL || 'http://127.0.0.1:8002';
(async () => {
  const browser = await chromium.launch({ headless: true });
  const findings = [];
  for (const width of [320, 375, 768, 1024, 1440]) {
    const page = await browser.newPage({ viewport: { width, height: 900 }, deviceScaleFactor: 1 });
    const errors = [];
    page.on('pageerror', error => errors.push(String(error)));
    page.on('response', response => { if (response.url().includes('/assets/') && response.status() >= 400) errors.push('asset ' + response.status() + ' ' + response.url()); });
    await page.addInitScript(() => localStorage.setItem('vf_cookie_notice_accepted', '1'));
    const response = await page.goto(baseUrl + '/ui-kit', { waitUntil: 'networkidle' });
    await page.evaluate(() => document.fonts.ready);
    const base = await page.evaluate(() => ({ scrollWidth: document.documentElement.scrollWidth, h1: document.querySelectorAll('h1').length, fontInter: document.fonts.check('16px Inter'), fontManrope: document.fonts.check('16px Manrope'), loadedFonts: [...new Set([...document.fonts].filter(f => f.status === 'loaded').map(f => f.family))] }));
    if (base.scrollWidth !== width) errors.push('document overflow');
    const section = page.locator('#navigation-preview');
    await section.screenshot({path: path.join(outputDir, `nav16-${width}-closed.png`)});
    for (const panel of ['features','audiences','company','user','mobile-features','mobile-audiences','crumbs']) {
      const trigger = page.locator(`[aria-controls="vf-ui-nav-${panel}"]`);
      await trigger.focus();
      await page.keyboard.press('Enter');
      if (await trigger.getAttribute('aria-expanded') !== 'true' || !await page.locator(`#vf-ui-nav-${panel}`).isVisible()) errors.push(`${panel}: failed open`);
      await section.screenshot({path: path.join(outputDir, `nav16-${width}-${panel}.png`)});
      await page.keyboard.press('Escape');
      if (await trigger.getAttribute('aria-expanded') !== 'false' || await page.locator(`#vf-ui-nav-${panel}`).isVisible()) errors.push(`${panel}: failed close`);
      if (!await trigger.evaluate(el => el === document.activeElement)) errors.push(`${panel}: focus not restored`);
    }
    const company = page.locator('[aria-controls="vf-ui-nav-company"]');
    await company.focus();
    await page.keyboard.press('Enter');
    await page.keyboard.press('Tab');
    if (!await page.locator('#vf-ui-nav-company-search').evaluate(el => el === document.activeElement)) errors.push('Tab did not enter company search');
    await page.keyboard.press('Escape');
    await company.click();
    if (await page.locator('[data-vf-ui-kit-company-empty]').evaluate(el => getComputedStyle(el).display === 'none')) errors.push('status removed from accessibility tree');
    await page.locator('[data-vf-ui-kit-company-search]').fill('нет такой');
    if (!await page.locator('[data-vf-ui-kit-company-empty]').isVisible()) errors.push('search empty missing');
    await page.locator('[data-vf-ui-kit-company-search]').fill('0000000001');
    if (await page.locator('[data-vf-ui-kit-company-option]:visible').count() !== 1) errors.push('INN search without spaces failed');
    await page.locator('[data-vf-ui-kit-company-search]').fill('ИНН 0000000001');
    if (await page.locator('[data-vf-ui-kit-company-option]:visible').count() !== 1) errors.push('prefixed INN search failed');
    await page.locator('[data-vf-ui-kit-company-search]').fill('ИНН: 000-000-0001');
    if (await page.locator('[data-vf-ui-kit-company-option]:visible').count() !== 1) errors.push('punctuated INN search failed');
    await page.locator('[data-vf-ui-kit-company-search]').fill('ИНН');
    if (await page.locator('[data-vf-ui-kit-company-option]:visible').count() !== 3) errors.push('incomplete INN prefix hid options');
    await page.locator('[data-vf-ui-kit-company-search]').fill('яа');
    if (await page.locator('[data-vf-ui-kit-company-option]:visible').count() !== 0) errors.push('name search crossed word boundary');
    await page.locator('[data-vf-ui-kit-company-search]').fill('демо000');
    if (await page.locator('[data-vf-ui-kit-company-option]:visible').count() !== 0) errors.push('cross-field search matched');
    await page.locator('[data-vf-ui-kit-company-search]').fill('Компания Б');
    await page.locator('[data-vf-ui-kit-company-option][data-initial="Б"]').click();
    if (!((await page.locator('[data-vf-ui-kit-company-name]').textContent()) || '').includes('Компания Б')) errors.push('selection failed');
    await company.click();
    if (await page.locator('[data-vf-ui-kit-company-search]').inputValue() !== '' || await page.locator('[data-vf-ui-kit-company-option]:visible').count() !== 3) errors.push('search did not reset');
    await page.keyboard.press('Escape');
    await page.locator('[aria-controls="vf-ui-nav-features"]').click();
    await page.locator('[aria-controls="vf-ui-nav-company"]').click();
    if (!await page.locator('#vf-ui-nav-features').isVisible() || !await page.locator('#vf-ui-nav-company').isVisible()) errors.push('independent panels');
    await section.screenshot({path: path.join(outputDir, `nav16-${width}-open.png`)});
    await page.locator('#navigation-preview-title').click();
    if (await page.locator('#vf-ui-nav-features').isVisible() || await page.locator('#vf-ui-nav-company').isVisible()) errors.push('outside click');
    const feature = page.locator('[aria-controls="vf-ui-nav-features"]');
    await feature.focus();
    await page.keyboard.press('Space');
    if (!await page.locator('#vf-ui-nav-features').isVisible()) errors.push('Space did not open features');
    await page.keyboard.press('Tab');
    if (!await page.locator('#vf-ui-nav-features').evaluate(panel => panel.contains(document.activeElement))) errors.push('Tab did not enter feature panel');
    await page.keyboard.press('Escape');
    if (!await feature.evaluate(el => el === document.activeElement)) errors.push('Escape did not restore feature focus');
    await feature.click();
    await feature.evaluate(el => el.blur());
    await page.keyboard.press('Escape');
    if (await page.locator('#vf-ui-nav-features').isVisible()) errors.push('Escape after unfocused click did not close');
    await feature.click();
    await page.locator('a[href]').first().focus();
    if (await page.locator('#vf-ui-nav-features').isVisible()) errors.push('focus departure did not close');
    const crumbs = page.locator('[aria-controls="vf-ui-nav-crumbs"]');
    await crumbs.click();
    if ((await crumbs.textContent()).trim() === '…') errors.push('expanded crumbs still show ellipsis');
    if (await crumbs.getAttribute('aria-label') !== 'Промежуточные разделы') errors.push('crumb accessible name changed');
    await page.keyboard.press('Escape');
    if ((await crumbs.textContent()).trim() !== '…') errors.push('collapsed crumbs lost ellipsis');
    findings.push({width, status: response.status(), ...base, panelStatesChecked: 7, keyboardChecked: ['Enter','Space','Tab','Escape'], outsideClickChecked: true, searchSelectionChecked: true, innSearchChecked: true, errors});
    await page.close();
  }
  const touchPage = await browser.newPage({viewport: {width: 375, height: 812}, hasTouch: true, isMobile: true});
  const touchErrors = [];
  const touchResponse = await touchPage.goto(baseUrl + '/ui-kit', {waitUntil: 'networkidle'});
  await touchPage.locator('[aria-controls="vf-ui-nav-features"]').tap();
  if (!await touchPage.locator('#vf-ui-nav-features').isVisible()) touchErrors.push('site panel tap failed');
  await touchPage.locator('[aria-controls="vf-ui-nav-company"]').tap();
  if (!await touchPage.locator('#vf-ui-nav-company').isVisible()) touchErrors.push('account panel tap failed');
  await touchPage.locator('[data-vf-ui-kit-company-option][data-initial="Б"]').tap();
  if (!((await touchPage.locator('[data-vf-ui-kit-company-name]').textContent()) || '').includes('Компания Б')) touchErrors.push('company selection tap failed');
  findings.push({width: 375, mode: 'touch', status: touchResponse.status(), errors: touchErrors});
  await touchPage.close();
  fs.writeFileSync(path.join(outputDir, 'nav16-findings.json'), JSON.stringify(findings, null, 2) + '\n');
  console.log(JSON.stringify(findings));
  if (findings.some(f => f.errors.length || f.status !== 200)) process.exitCode = 1;
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
