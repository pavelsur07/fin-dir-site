## Unit-экономика: где товар реально прибыльный

Один и тот же товар может быть прибыльным на сайте и убыточным на маркетплейсе. Причина — разные правила расчёта: комиссия, логистика, скидки, реклама, возвраты и операционные расходы.

Для сравнения каналов нужно считать не «продали на 1 млн», а маржу после всех прямых расходов. Минимальная формула для SKU:

- выручка по товару;
- минус себестоимость;
- минус комиссия площадки или платёжные расходы;
- минус логистика, хранение, эквайринг, возвраты;
- минус реклама и скидки;
- итог — вклад товара в прибыль.

> **Best practice:** сравнивать каналы по CM1/CM2/CM3 и смотреть прибыльность в разрезе SKU, категории и рекламной кампании. Иначе прибыльные товары будут смешиваться с убыточными.

## Деньги и кассовый разрыв

Прибыль на бумаге не означает, что деньги есть на счёте. На маркетплейсах деньги могут приходить с задержкой, часть средств удерживается, возвраты и штрафы появляются позже, а поставщику платить нужно раньше.

У интернет-магазина cash flow тоже требует контроля: реклама оплачивается заранее, товар закупается до продажи, доставка и сервис создают кассовую нагрузку. Поэтому оба канала нужно планировать через платёжный календарь.

### Что отслеживать еженедельно

- остаток денег сейчас и прогноз на 30 дней;
- обязательства перед поставщиками, подрядчиками и налогами;
- ожидаемые выплаты от маркетплейсов;
- план закупок и рекламный бюджет;
- товары, которые замораживают деньги в остатках.

## Когда выгоднее маркетплейс, а когда сайт

Маркетплейс подходит, если нужно быстро проверить спрос, выйти на широкую аудиторию и протестировать ассортимент. Но он требует дисциплины в учёте, потому что мелкие удержания и комиссии быстро съедают маржу.

Интернет-магазин выгоднее, когда у бизнеса есть повторные продажи, бренд, контент, сильная ниша или возможность строить долгосрочные отношения с клиентом. Но без системы трафика и аналитики он может стать дорогим экспериментом.

### Маркетплейс чаще выбирают, когда:

- нужно быстро получить первые продажи;
- товар уже понятен рынку;
- есть готовность играть по правилам площадки;
- важна скорость запуска, а не полный контроль.

### Интернет-магазин чаще выбирают, когда:

- есть бренд и понятная аудитория;
- важны повторные продажи и клиентская база;
- можно управлять трафиком и CRM;
- нужен контроль над ценой, ассортиментом и коммуникацией.

## Мультиканальность как рабочая стратегия

На практике сильное решение — не выбирать один канал навсегда, а выстроить управляемую систему продаж. Маркетплейсы могут давать быстрый спрос и тест гипотез, а сайт — повторные продажи, бренд и базу клиентов.

Но мультиканальность работает только при нормальном учёте. Без единой системы собственник видит много отчётов, но не понимает, какой канал действительно приносит прибыль.

> **Финансовая система должна отвечать на три вопроса:**
>
> - какой канал приносит прибыль, а какой только оборот;
> - какие SKU нужно масштабировать, а какие замораживают деньги;
> - сколько денег понадобится на закупки, рекламу и рост.

## Интернет-магазин или маркетплейс: частые вопросы

### Какой канал выгоднее для старта?

Для быстрого теста спроса чаще проще маркетплейс. Но решение зависит от категории, маржи, конкуренции, логистики и рекламных расходов.

### Почему при росте выручки может не быть денег?

Потому что деньги могут быть в остатках, дебиторке, рекламе, задержках выплат, возвратах и обязательствах перед поставщиками. Поэтому нужен ДДС и платёжный календарь.

### Что считать главным показателем?

Не один показатель, а связку: валовая прибыль, вклад SKU в маржу, рекламная эффективность, остатки, cash flow и EBITDA.

### Можно ли совмещать маркетплейс и интернет-магазин?

Да, но важно разделять экономику каналов и не смешивать расходы. Иначе невозможно понять, где бизнес зарабатывает, а где теряет.
